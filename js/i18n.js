// ===== LANGUAGE ENGINE =====
let LANG = localStorage.getItem('cvpro_lang') || 'fr';

function t(key) {
  return (I18N[LANG] && I18N[LANG][key]) || (I18N['fr'][key]) || key;
}

function setLang(lang) {
  LANG = lang;
  localStorage.setItem('cvpro_lang', lang);
  applyTranslations();
  updateLangSwitcher();
  document.documentElement.lang = lang;
}

function applyTranslations() {
  // Apply all [data-i18n] attributes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const attr = el.getAttribute('data-i18n-attr');
    const val = t(key);
    if (attr) {
      el.setAttribute(attr, val);
    } else {
      el.textContent = val;
    }
  });
  // Apply [data-i18n-html] for innerHTML (trusted content only)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    el.innerHTML = t(key);
  });
}

function updateLangSwitcher() {
  document.querySelectorAll('.lang-btn').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === LANG);
  });
}

// Auto-init on DOMContentLoaded
document.addEventListener('DOMContentLoaded', () => {
  LANG = localStorage.getItem('cvpro_lang') || 'fr';
  document.documentElement.lang = LANG;
  applyTranslations();
  updateLangSwitcher();
});
